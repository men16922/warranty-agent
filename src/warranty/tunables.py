"""대기·창 길이 — **한 모듈에만** 있다 (REQ-804).

Spec: specs/warranty/design/11-demo.md §5
      specs/warranty/design/02-verification.md §4
      (REQ-206, REQ-804)

영상 재촬영 전에 손대는 값들이다. design 11§2가 *"타이머를 줄인다"*라고 말하는 그
타이머가 여기 있고, **여기 말고 다른 곳에는 없다.**

⚠️ 값이 흩어지면 재촬영 때 **반드시 하나를 놓친다.** 놓친 쪽은 예전 값으로 계속 돌고,
   그 어긋남은 조용하다 — 게이트는 초록이고 영상만 이상해진다.
   그래서 이것은 관례가 아니라 **집행되는 규칙이다**: `tests/test_tunables.py`가
   ① 이 모듈 밖의 대기·창 상수 정의와 ② 호출부에 박힌 숫자 리터럴을 red로 만든다.

⚠️ 이 모듈은 아무것도 임포트하지 않는다(`Decimal` 하나 빼고). **값만 있는 자리**여야
   누구나 순환 임포트 걱정 없이 여기를 가리킬 수 있다.
"""

from __future__ import annotations

from decimal import Decimal

#: 재측정 창. 기준선과 재측정이 **같은 창**을 써야 두 값이 비교 가능하다 (REQ-202).
VERIFY_WINDOW_S = 120

#: 조치가 신호에 반영되기까지 기다리는 시간.
#:
#: ⛔ **이 값은 반드시 `VERIFY_WINDOW_S`보다 커야 한다.** 그렇지 않으면 재측정 창이
#:    조치 **이전** 구간을 물고, "after"가 before와 after의 혼합이 된다.
#:    45였던 동안 창 120초 중 **75초가 조치 전 데이터**였고, 그래서 트래픽을 건강한
#:    리비전으로 되돌려도 판정이 `not_recovered`로 나왔다 —
#:    **검증이 구조적으로 실패 쪽으로 기울어 있었다.**
#:    2026-08-30 실물에서 잡았다: `traffic:demo-target-00001-swl`(건강한 쪽)이
#:    `not_recovered`를 받았다. 증거 `docs/evidence/verify-window-2026-08-30.log`.
#: ⚠️ 이것을 줄이고 싶은 유혹은 촬영 시간 때문에 온다. 줄이면 **아직 안 온 데이터로
#:    판정**하게 되고, 그건 이 저장소가 통째로 반대하는 짓이다.
#: ⚠️ 여유 15초는 Cloud Monitoring의 도착 지연 몫이다 (design 02§4).
VERIFY_DELAY_S = VERIFY_WINDOW_S + 15

#: 조치 한 건이 기다리는 **횟수**. ⚠️ 둘이다 — 조치 후 재측정(REQ-202)과
#: **롤백 후 재측정**(REQ-304). 롤백까지 가는 경로가 가장 길다.
WAITS_PER_REMEDIATION = 2

#: 요청 타임아웃. ⛔ **검증 대기의 총합보다 길어야 한다.**
#: 짧으면 에이전트가 재측정하는 **도중에 요청이 끊긴다** — 조치는 이미 실물에 나갔고
#: 원장에도 남는데, 그 판정을 **부른 사람이 못 본다.** 서버는 완주하므로 기록은 옳다.
#: ⇒ 사라지는 것은 답뿐이고, 그래서 더 조용하다.
#: ⚠️ 2026-08-30 실물: Cloud Run 기본값 300초(우리가 **안 적어서** 생긴 값)에서
#:    롤백 경로 2×135=270초 + 모델 왕복이 넘어갔다.
#: ⚠️ 2배 여유는 모델 왕복 몫이다. 늘려도 과금이 늘지 않는다 — Cloud Run은 타임아웃이
#:    아니라 **실제로 쓴 시간**에 과금한다.
REQUEST_TIMEOUT_S = 2 * WAITS_PER_REMEDIATION * VERIFY_DELAY_S

#: 데모 한 판이 쓸 수 있는 예산. 게이트의 세 번째 축(headroom)이 이것을 읽는다.
DEMO_BUDGET_USD = Decimal("0.50")

#: 촬영 전 콜드 스타트를 녹이는 요청 수. `min-instances=0`이라 첫 요청이 느리다
#: (design 11§4). ⛔ **아직 이것을 읽는 코드가 없다** — 워밍은 T8-3(촬영) 절차이고
#: 코드 경로가 아니다. 그래도 여기 있는 이유는 design 11§5가 이 이름을 선언하기
#: 때문이고, 선언과 코드가 어긋나면 `tests/test_tunables.py`가 red다.
#: 값을 여기 두는 것과 **읽는 곳이 생기는 것**은 다른 일이다.
WARMUP_REQUESTS = 1
